const dynamicTranslations: Array<[RegExp, string]> = [
  [/^(\d+) yeni fırsat bekliyor$/, "$1 فرصت تازه در انتظار بررسی است"],
  [/^(\d+) araç kısa listede$/, "$1 خودرو در فهرست منتخب است"],
  [/^(\d+) kaynakta sorun var$/, "$1 منبع مشکل دارد"],
  [/^Kaynaklar: (.+)$/, "منابع: $1"],
  [/^Filtre: (.+)$/, "فیلتر: $1"],
  [/^Son (\d+) saat$/, "$1 ساعت اخیر"],
  [/^([\d.,]+) km$/, "$1 کیلومتر"],
];

export function translateToFa(value: string) {
  const normalized = value.trim();
  const exact = faTranslations[normalized];
  if (exact) return value.replace(normalized, exact);
  for (const [pattern, replacement] of dynamicTranslations) {
    if (pattern.test(normalized)) return value.replace(normalized, normalized.replace(pattern, replacement));
  }
  return value;
}
